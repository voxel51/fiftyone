"""
Generates ``fiftyone/_voodoo_palette.py`` from the installed
``@voxel51/voodo`` dependency.

The App imports the palette from ``@voxel51/voodo/tokens`` directly. Python
cannot import from an npm package, so this script runs ``node`` against the
dependency the App already has installed and writes what it reads to a module
that ``fiftyone/constants.py`` imports.

Usage::

    python tools/sync_voodoo_palette.py           # write the module
    python tools/sync_voodoo_palette.py --check   # exit 1 if stale (CI)

Requires the App's dependencies to be installed (``yarn install`` in ``app/``).

The pool read here is Voodo's ``viz-overlay`` group, not ``viz-chart``. The
distinction is the whole reason the design system splits them: overlay colors
are drawn *on media* -- detection boxes, masks, keypoints -- and the image
behind them does not get lighter when the UI does, so they are identical in
both themes. Chart colors are drawn on the UI and do follow the theme.

That makes this script mode-independent by construction. It previously took the
dark-mode values and noted that the server is not theme-aware; there is no
longer a mode to choose.

| Copyright 2017-2025, Voxel51, Inc.
| `voxel51.com <https://voxel51.com/>`_
|
"""

import argparse
import json
import os
import subprocess
import sys


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

APP_DIR = os.path.join(REPO_ROOT, "app")

TARGET = os.path.join(REPO_ROOT, "fiftyone", "_voodoo_palette.py")

# Run from app/ so node resolves @voxel51/voodo out of the App's node_modules.
# `paletteSlots` names each slot's hue and `primitives` gives the scale step it
# came from ("teal 400"), which is how the design system names these.
_READ_TOKENS = """
import("@voxel51/voodo/tokens").then(
  ({ overlayPool, paletteSlots, primitives, colors }) =>
    console.log(
      JSON.stringify({
        pool: overlayPool,
        slots: paletteSlots,
        primitives,
        brand: colors.common.brand,
      })
    )
);
"""

_TEMPLATE = '''"""
Voodo design system color palette.

AUTO-GENERATED by ``tools/sync_voodoo_palette.py`` -- do not edit by hand.
Run that script to pick up design system changes.

| Copyright 2017-2025, Voxel51, Inc.
| `voxel51.com <https://voxel51.com/>`_
|
"""

# The App's default color pool, in the order colors are handed out
COLOR_POOL = [
{entries}
]

# Brand colors. Mode-independent -- they are the same in light and dark.
BRAND_PRIMARY = "{brand_primary}"
BRAND_ACCENT = "{brand_accent}"
'''


def _read_tokens():
    """Reads the palette from the installed ``@voxel51/voodo``.

    Returns:
        a ``(pool, slots, primitives, brand)`` tuple

    Raises:
        SystemExit: if node is unavailable or the dependency cannot be read
    """
    try:
        result = subprocess.run(
            ["node", "--input-type=module", "-e", _READ_TOKENS],
            capture_output=True,
            cwd=APP_DIR,
            text=True,
        )
    except FileNotFoundError as error:
        raise SystemExit("node is required to read @voxel51/voodo") from error

    if result.returncode != 0:
        raise SystemExit(
            "Could not read @voxel51/voodo/tokens. Install the App's "
            "dependencies (`yarn install` in app/) and make sure the "
            "installed version exports the tokens subpath.\n\n%s"
            % result.stderr.strip()
        )

    tokens = json.loads(result.stdout)

    return (
        tokens["pool"],
        tokens.get("slots", []),
        tokens.get("primitives", {}),
        tokens.get("brand", {}),
    )


def _render(pool, slots, primitives, brand=None):
    """Renders the generated module.

    Args:
        pool: the ordered palette colors
        slots: the hue name for each slot, in the same order as ``pool``
        primitives: the design system's raw color scales, used for labels
        brand (None): the mode-independent brand colors

    Returns:
        the module source, black-formatted at 79 columns
    """
    brand = brand or {}
    labels = {}
    for scale, steps in primitives.items():
        for step, value in steps.items():
            labels.setdefault(value, "%s %s" % (scale, step))

    entries = []
    for i, color in enumerate(pool, 1):
        hue = slots[i - 1] if i <= len(slots) else "unnamed"
        step = labels.get(color)
        # The hue name is the token's own name; the step is its provenance in
        # the primitive scales. They usually agree, and disagreeing is worth
        # seeing -- it means the semantic token points at another hue's ramp.
        detail = hue if step is None else "%s (%s)" % (hue, step)
        entries.append('    "%s",  # %d: %s' % (color, i, detail))

    return _TEMPLATE.format(
        entries="\n".join(entries),
        brand_primary=brand.get("primary", ""),
        brand_accent=brand.get("accent", ""),
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the generated module is stale; write nothing",
    )
    args = parser.parse_args()

    module = _render(*_read_tokens())
    try:
        relative = os.path.relpath(TARGET, REPO_ROOT)
    except ValueError:
        # Windows raises when the two paths sit on different drives
        relative = TARGET

    current = None
    if os.path.isfile(TARGET):
        with open(TARGET, "rt") as f:
            current = f.read()

    if current == module:
        print("%s is up to date" % relative)
        return 0

    if args.check:
        print(
            "%s is out of date with @voxel51/voodo.\n"
            "Run `python tools/sync_voodoo_palette.py` and commit the result."
            % relative,
            file=sys.stderr,
        )
        return 1

    with open(TARGET, "wt") as f:
        f.write(module)

    print("Wrote %s" % relative)

    return 0


if __name__ == "__main__":
    sys.exit(main())
