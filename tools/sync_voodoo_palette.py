"""
Syncs ``DEFAULT_APP_COLOR_POOL`` in ``fiftyone/constants.py`` from the Voodo
design system's color tokens.

The App reads palette colors from CSS variables generated by
``@voxel51/voodo``, but the Python default color pool is a hardcoded list, so
the two drift silently whenever the design system changes. This script makes
the design system the single source of truth: it reads the palette out of the
installed ``@voxel51/voodo`` package and rewrites the generated block in
``constants.py``.

Usage::

    # rewrite constants.py
    python tools/sync_voodoo_palette.py

    # exit 1 if out of date (CI)
    python tools/sync_voodoo_palette.py --check

    # print the block instead of writing it
    python tools/sync_voodoo_palette.py --print

The palette is theme-aware in the App but not on the server, so the dark-mode
values are used -- dark is the App's default theme. Light and dark palettes are
identical today; if they ever diverge, this choice needs revisiting alongside
whatever makes the server theme-aware.

| Copyright 2017-2025, Voxel51, Inc.
| `voxel51.com <https://voxel51.com/>`_
|
"""

import argparse
import json
import os
import sys


# The ordered palette slots handed out by the App, mirroring PALETTE_POOL_KEYS
# in @voxel51/voodo (src/theme/useColorPalette.ts).
POOL_SLOTS = [str(i) for i in range(1, 13)]

BEGIN_MARKER = (
    "# BEGIN generated palette -- run tools/sync_voodoo_palette.py to update"
)
END_MARKER = "# END generated palette"

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CONSTANTS_PATH = os.path.join(REPO_ROOT, "fiftyone", "constants.py")

# Where the tokens land depends on how the App's node_modules were hoisted, so
# check the workspace root first and then the package that declares the
# dependency
TOKENS_CANDIDATES = [
    os.path.join(
        REPO_ROOT, "app", "node_modules", "@voxel51", "voodo", "tokens.json"
    ),
    os.path.join(
        REPO_ROOT,
        "app",
        "node_modules",
        "@voxel51",
        "voodo",
        "dist",
        "tokens.json",
    ),
    os.path.join(
        REPO_ROOT,
        "app",
        "packages",
        "components",
        "node_modules",
        "@voxel51",
        "voodo",
        "dist",
        "tokens.json",
    ),
]


def _find_tokens(explicit=None, skip_if_missing=False):
    """Locates the Voodo ``tokens.json``.

    Args:
        explicit (None): an explicit path, e.g. a local design-system checkout
        skip_if_missing (False): return ``None`` instead of raising when the
            tokens cannot be found

    Returns:
        the path to ``tokens.json``, or ``None``
    """
    if explicit is not None:
        if not os.path.isfile(explicit):
            raise SystemExit("No tokens.json at '%s'" % explicit)

        return explicit

    env = os.environ.get("VOODO_TOKENS")
    if env:
        return _find_tokens(env)

    for path in TOKENS_CANDIDATES:
        if os.path.isfile(path):
            return path

    if skip_if_missing:
        return None

    raise SystemExit(
        "Could not find @voxel51/voodo tokens.json. Install the App's "
        "dependencies (`yarn install` in app/), or pass --tokens with the "
        "path to a design-system checkout's src/theme/tokens.json."
    )


def _load_palette(tokens_path):
    """Extracts the ordered dark-mode palette from the Voodo tokens.

    Args:
        tokens_path: the path to ``tokens.json``

    Returns:
        a list of ``(hex, label)`` tuples in pool order
    """
    with open(tokens_path, "rt") as f:
        tokens = json.load(f)

    try:
        palette = tokens["colors"]["dark"]["content"]["palette"]
    except KeyError:
        raise SystemExit(
            "Unexpected token shape in '%s': no colors.dark.content.palette. "
            "The design system's token tree may have been restructured."
            % tokens_path
        )

    # Reverse the primitive scales so each slot can be labeled with the scale
    # step it came from ("purple 600"), which is how the design system talks
    # about these colors
    labels = {}
    for scale, steps in tokens.get("primitives", {}).items():
        for step, value in steps.items():
            labels.setdefault(value, "%s %s" % (scale, step))

    pool = []
    for slot in POOL_SLOTS:
        if slot not in palette:
            raise SystemExit(
                "Palette slot %s missing from '%s'" % (slot, tokens_path)
            )

        color = palette[slot]
        pool.append((color, labels.get(color, "unmapped")))

    return pool


def _render(pool):
    """Renders the generated ``constants.py`` block.

    Args:
        pool: a list of ``(hex, label)`` tuples

    Returns:
        the block, black-formatted at 79 columns
    """
    lines = [BEGIN_MARKER, "DEFAULT_APP_COLOR_POOL = ["]
    for i, (color, label) in enumerate(pool, 1):
        lines.append('    "%s",  # %d: %s' % (color, i, label))

    lines.append("]")
    lines.append(END_MARKER)

    return "\n".join(lines)


def _splice(source, block):
    """Replaces the marked block in ``source``.

    Args:
        source: the contents of ``constants.py``
        block: the rendered block

    Returns:
        the updated contents
    """
    start = source.find(BEGIN_MARKER)
    end = source.find(END_MARKER)
    if start < 0 or end < 0:
        raise SystemExit(
            "Could not find the generated palette markers in '%s'. Restore "
            "them around DEFAULT_APP_COLOR_POOL:\n\n%s\n"
            "DEFAULT_APP_COLOR_POOL = [...]\n%s"
            % (CONSTANTS_PATH, BEGIN_MARKER, END_MARKER)
        )

    return source[:start] + block + source[end + len(END_MARKER) :]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if constants.py is out of date; write nothing",
    )
    parser.add_argument(
        "--print",
        action="store_true",
        dest="print_only",
        help="print the generated block instead of writing it",
    )
    parser.add_argument(
        "--tokens",
        default=None,
        help="path to a Voodo tokens.json, e.g. from a local checkout",
    )
    parser.add_argument(
        "--skip-if-missing",
        action="store_true",
        help=(
            "succeed quietly when the installed @voxel51/voodo predates the "
            "tokens.json export, rather than failing (for CI)"
        ),
    )
    args = parser.parse_args()

    tokens_path = _find_tokens(args.tokens, args.skip_if_missing)
    if tokens_path is None:
        print(
            "No @voxel51/voodo tokens.json found; skipping palette sync. "
            "Upgrade @voxel51/voodo to a version that exports tokens.json."
        )
        return 0

    block = _render(_load_palette(tokens_path))

    if args.print_only:
        print(block)
        return 0

    with open(CONSTANTS_PATH, "rt") as f:
        source = f.read()

    updated = _splice(source, block)

    if updated == source:
        print("DEFAULT_APP_COLOR_POOL is up to date with %s" % tokens_path)
        return 0

    if args.check:
        print(
            "DEFAULT_APP_COLOR_POOL is out of date with %s.\n"
            "Run `python tools/sync_voodoo_palette.py` and commit the result."
            % tokens_path,
            file=sys.stderr,
        )
        return 1

    with open(CONSTANTS_PATH, "wt") as f:
        f.write(updated)

    print("Updated %s from %s" % (CONSTANTS_PATH, tokens_path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
