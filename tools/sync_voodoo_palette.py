"""
Generates ``fiftyone/_voodoo_palette.py`` from the Voodo design system's color
tokens.

The App renders palette colors from CSS variables generated by
``@voxel51/voodo``, and the App's TypeScript reads the pool straight from
``@voxel51/voodo/tokens``. Python cannot import from an npm package, so this
script closes that gap: it reads the palette out of the installed
``@voxel51/voodo`` and writes a generated module that ``fiftyone/constants.py``
imports.

The output is a wholly generated module, not a block edited into an existing
file. Nothing here parses the file it writes, and the module is imported like
any other, so a rename or a shape change fails loudly rather than silently
producing a wrong palette. ``--check`` covers the one thing that cannot catch:
whether the committed values are stale with respect to the tokens.

Usage::

    # regenerate the module
    python tools/sync_voodoo_palette.py

    # exit 1 if it is out of date (CI)
    python tools/sync_voodoo_palette.py --check

    # print the module instead of writing it
    python tools/sync_voodoo_palette.py --print

The palette is theme-aware in the App but not on the server, so the dark-mode
values are used -- dark is the App's default theme. Light and dark palettes are
identical today; if they ever diverge, this choice needs revisiting alongside
whatever makes the server theme-aware.

| Copyright 2017-2025, Voxel51, Inc.
| `voxel51.com <https://voxel51.com/>`_
|
"""

import argparse
import json
import os
import sys


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PYTHON_TARGET = os.path.join(REPO_ROOT, "fiftyone", "_voodoo_palette.py")

# Where the tokens land depends on how the App's node_modules were hoisted, so
# check the workspace root first and then the package that declares the
# dependency
TOKENS_CANDIDATES = [
    os.path.join(
        REPO_ROOT, "app", "node_modules", "@voxel51", "voodo", "tokens.json"
    ),
    os.path.join(
        REPO_ROOT,
        "app",
        "node_modules",
        "@voxel51",
        "voodo",
        "dist",
        "tokens.json",
    ),
    os.path.join(
        REPO_ROOT,
        "app",
        "packages",
        "components",
        "node_modules",
        "@voxel51",
        "voodo",
        "dist",
        "tokens.json",
    ),
]

_PYTHON_TEMPLATE = '''"""
Voodo design system color palette.

AUTO-GENERATED by ``tools/sync_voodoo_palette.py`` -- do not edit by hand.
Run that script to pick up design system changes.

| Copyright 2017-2025, Voxel51, Inc.
| `voxel51.com <https://voxel51.com/>`_
|
"""

# The App's default color pool, in the order colors are handed out
COLOR_POOL = [
{entries}
]
'''


def _find_tokens(explicit=None, skip_if_missing=False):
    """Locates the Voodo ``tokens.json``.

    Args:
        explicit (None): an explicit path, e.g. a local design-system checkout
        skip_if_missing (False): return ``None`` instead of raising when the
            tokens cannot be found

    Returns:
        the path to ``tokens.json``, or ``None``
    """
    if explicit is not None:
        if not os.path.isfile(explicit):
            raise SystemExit("No tokens.json at '%s'" % explicit)

        return explicit

    env = os.environ.get("VOODO_TOKENS")
    if env:
        return _find_tokens(env)

    for path in TOKENS_CANDIDATES:
        if os.path.isfile(path):
            return path

    if skip_if_missing:
        return None

    raise SystemExit(
        "Could not find @voxel51/voodo tokens.json. Install the App's "
        "dependencies (`yarn install` in app/), or pass --tokens with the "
        "path to a design-system checkout's src/theme/tokens.json."
    )


def _load_palette(tokens_path):
    """Extracts the ordered dark-mode palette from the Voodo tokens.

    Args:
        tokens_path: the path to ``tokens.json``

    Returns:
        a list of ``(hex, label)`` tuples in pool order
    """
    with open(tokens_path, "rt") as f:
        tokens = json.load(f)

    try:
        palette = tokens["colors"]["dark"]["content"]["palette"]
    except KeyError:
        raise SystemExit(
            "Unexpected token shape in '%s': no colors.dark.content.palette. "
            "The design system's token tree may have been restructured."
            % tokens_path
        )

    # Reverse the primitive scales so each slot can be labeled with the scale
    # step it came from ("purple 600"), which is how the design system talks
    # about these colors
    labels = {}
    for scale, steps in tokens.get("primitives", {}).items():
        for step, value in steps.items():
            labels.setdefault(value, "%s %s" % (scale, step))

    # A palette is N colors, not a fixed count: take whatever numbered slots
    # the tokens define, in ascending numeric order. The named aliases
    # (orange, teal, ...) sit alongside them but are excluded -- they name a
    # specific hue rather than a slot to hand out. Mirrors paletteSlots in
    # @voxel51/voodo (src/theme/tokens/palette.ts).
    slots = sorted(
        (key for key in palette if key.isdigit()),
        key=int,
    )

    if not slots:
        raise SystemExit(
            "No numbered palette slots in '%s'. The design system's token "
            "tree may have been restructured." % tokens_path
        )

    return [
        (palette[slot], labels.get(palette[slot], "unmapped"))
        for slot in slots
    ]


def _render_python(pool):
    """Renders the generated Python module.

    Args:
        pool: a list of ``(hex, label)`` tuples

    Returns:
        the module source, black-formatted at 79 columns
    """
    entries = [
        '    "%s",  # %d: %s' % (color, i, label)
        for i, (color, label) in enumerate(pool, 1)
    ]

    return _PYTHON_TEMPLATE.format(entries="\n".join(entries))


def _read(path):
    """Reads ``path``, or returns ``None`` if it does not exist."""
    if not os.path.isfile(path):
        return None

    with open(path, "rt") as f:
        return f.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the generated module is out of date",
    )
    parser.add_argument(
        "--print",
        action="store_true",
        dest="print_only",
        help="print the generated module instead of writing it",
    )
    parser.add_argument(
        "--tokens",
        default=None,
        help="path to a Voodo tokens.json, e.g. from a local checkout",
    )
    parser.add_argument(
        "--skip-if-missing",
        action="store_true",
        help=(
            "succeed quietly when the installed @voxel51/voodo predates the "
            "tokens.json export, rather than failing (for CI)"
        ),
    )
    args = parser.parse_args()

    tokens_path = _find_tokens(args.tokens, args.skip_if_missing)
    if tokens_path is None:
        print(
            "No @voxel51/voodo tokens.json found; skipping palette sync. "
            "Upgrade @voxel51/voodo to a version that exports tokens.json."
        )
        return 0

    module = _render_python(_load_palette(tokens_path))
    relative = os.path.relpath(PYTHON_TARGET, REPO_ROOT)

    if args.print_only:
        print(module)
        return 0

    if _read(PYTHON_TARGET) == module:
        print("%s is up to date with %s" % (relative, tokens_path))
        return 0

    if args.check:
        print(
            "%s is out of date with %s.\n"
            "Run `python tools/sync_voodoo_palette.py` and commit the result."
            % (relative, tokens_path),
            file=sys.stderr,
        )
        return 1

    with open(PYTHON_TARGET, "wt") as f:
        f.write(module)

    print("Wrote %s" % relative)

    return 0


if __name__ == "__main__":
    sys.exit(main())
